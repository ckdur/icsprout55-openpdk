#!/usr/bin/env python3
"""
Translate a (TVF-expanded) Calibre SVRF LVS deck into a KLayout LVS deck.

  svrf2klayout_lvs.py expanded_lvs.svrf out.lvs

Run-time variables (klayout -rd):
  input, topcell        layout
  schematic             reference netlist (CDL/SPICE)
  report                .lvsdb output
  target_netlist        extracted netlist output (SPICE)
  run_mode              deep (default) | flat
  thr / threads
  no_compare=1          only extract
  <SWITCH>=<value>      override any #DEFINE switch
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import svrf_parse as P  # noqa: E402
from svrf2klayout import Gen, rb_str  # noqa: E402


class LvsGen(Gen):
    def gen_stmts(self, stmts, ind, sc, in_rule=False):
        for s in stmts:
            k = s[0]
            if k == 'rule':
                continue  # ERC checks are not translated
            if k == 'text_layer' or k == 'port_text':
                continue
            if k == 'directive':
                m = re.match(r'LVS FILTER (\w+) \( (\w+) \) (OPEN|SHORT)', s[1], re.I)
                if m:
                    self.emit('sv_filter(%s, %s, %s)' % (rb_str(m.group(1)), rb_str(m.group(2)),
                                                         rb_str(m.group(3).upper())), ind)
                continue
            if k == 'attach':
                specs = self.layer_specs(s[1], text=True) + self.layer_specs(s[1])
                specs = sorted(set(specs))
                self.emit('sv_attach(%s, %s)' % (repr([list(x) for x in specs]), rb_str(s[2])), ind)
                continue
            if k == 'device':
                _, dtype, model, seed, pins, aux, macro, extra, ln = s
                pl = '[' + ', '.join('[%s, %s]' % (rb_str(l), rb_str(p or '')) for l, p in pins) + ']'
                self.emit('sv_device(%s, %s, %s, %s, %s)' % (rb_str(dtype), rb_str(model) if model else 'nil',
                                                             rb_str(seed), pl,
                                                             rb_str(macro[0]) if macro else 'nil'), ind)
                continue
            if k == 'ifdef':
                _, name, val, neg, body, other = s
                cond = 'sv_ifdef(%s, %s)' % (rb_str(name), rb_str(val) if val is not None else 'nil')
                if neg:
                    cond = '!' + cond
                self.emit('if %s' % cond, ind)
                self.gen_stmts(body, ind + 1, sc, in_rule)
                if other:
                    self.emit('else', ind)
                    self.gen_stmts(other, ind + 1, sc, in_rule)
                self.emit('end', ind)
                continue
            Gen.gen_stmts(self, [s], ind, sc, in_rule)


PRELUDE = r'''# frozen_string_literal: false
# ============================================================================
# KLayout LVS deck for {name}
#
# AUTOMATICALLY GENERATED by hacking/svrf2klayout/svrf2klayout_lvs.py from the
# Calibre SVRF deck {src}
# Do not edit by hand: edit the translator/runtime and regenerate.
# ============================================================================

$sv_exec_start = Time.now

if $input
  if $topcell
    source($input, $topcell)
  else
    source($input)
  end
end

report_lvs($report) if $report

$sv_flat = ($run_mode.to_s == "flat")
if $sv_flat
  flat
else
  deep
end
threads(($threads || $thr || "4").to_i)
verbose(false)

$sv_verbose = false
$sv_strict = false
$sv_select = nil
$sv_unselect = nil
$sv_failed = []
$sv_defines = {{}}
$sv_overrides = {{}}
$sv_switches = {{}}
{overrides}
'''

POSTLUDE = r'''
sv_lvs_extract

if $schematic
  require 'tmpdir'
  # CDL libraries repeat helper subcircuits (INV, TG, ...): keep the first
  # definition of each (a warning is logged if a later one differs)
  src = File.read($schematic, :encoding => "iso-8859-1")
  outl = []
  seen = {}
  cur = nil
  curname = nil
  src.each_line do |line|
    if line =~ /^\s*\.subckt\s+(\S+)/i
      curname = $1
      cur = [line]
    elsif cur
      cur << line
      if line =~ /^\s*\.ends/i
        body = cur.join
        # declare parameters used in the body (W=nw ...) on the .SUBCKT line
        prm = body.scan(/=\s*([A-Za-z_]\w*)/).flatten.uniq.reject { |x| x =~ /^[0-9]/ }
        unless prm.empty?
          hl = cur[0].chomp
          body = hl + " " + prm.collect { |x| "#{x}=1e-6" }.join(" ") + "\n" + cur[1..-1].join
        end
        if seen.has_key?(curname)
          log("SVRF LVS: subcircuit #{curname} redefined differently - first definition used") if seen[curname] != body
        else
          seen[curname] = body
          outl << body
        end
        cur = nil
      end
    else
      outl << line
    end
  end
  require 'securerandom'
  tmp = File.join(Dir.tmpdir, "sv_schematic_#{Process.pid}_#{SecureRandom.hex(8)}.cdl")
  File.write(tmp, outl.join)
  reader = RBA::NetlistSpiceReader::new(SvSpiceReader::new($sv_custom_classes))
  schematic(tmp, reader)
  schematic.top_circuit_count  # force reading
  File.delete(tmp) rescue nil
end

# LVS FILTER <device> OPEN: remove the devices
$sv_filters.each do |type, model, mode|
  netlist.each_circuit do |c|
    dl = []
    c.each_device { |d| dl << d if d.device_class.name == model }
    dl.each { |d| c.remove_device(d) }
  end
end

# Calibre compares flat (no HCELLs): flatten unless -rd hier=1
if $hier.to_s != "1"
  tc = netlist.circuit_by_name($topcell || source.cell_name)
  netlist.flatten_circuits(netlist.each_circuit.select { |c| c != tc }) if tc
end

# Calibre: LVS REDUCE PARALLEL MOS / RESISTORS ... YES
netlist.combine_devices
netlist.make_top_level_pins
begin
  # LVS REDUCE SPLIT GATES YES
  netlist.combine_devices if sv_reduce_split_gates(netlist) > 0
end
netlist.purge
netlist.purge_nets

if $target_netlist
  target_netlist($target_netlist, write_spice(true, false), "Extracted by KLayout with the ICS55 LVS deck")
end

if $schematic && $no_compare.to_s != "1"
  if $hier.to_s != "1"
    stc = schematic.circuit_by_name($topcell || source.cell_name)
    schematic.flatten_circuits(schematic.each_circuit.select { |c| c != stc }) if stc
  end
  schematic.combine_devices
  schematic.combine_devices if sv_reduce_split_gates(schematic) > 0
  schematic.purge
  align
  # only W and L (MOS, resistors) are traced, as in the Calibre deck
  netlist.each_device_class do |c|
    next unless c.has_parameter?("W") && c.has_parameter?("L")
    # TRACE PROPERTY tolerance of the Calibre deck (percent)
    tol = (c.is_a?(RBA::DeviceClassMOS4Transistor) ? {mos_err} : {res_err}) / 100.0
    eq = RBA::EqualDeviceParameters::new(c.parameter_id("W"), 1e-9, tol) +
         RBA::EqualDeviceParameters::new(c.parameter_id("L"), 1e-9, tol)
    c.equal_parameters = eq
    sc = schematic.device_class_by_name(c.name)
    sc.equal_parameters = eq if sc
  end
  [netlist, schematic].each do |nl|
    nl.each_device_class do |c|
      if c.is_a?(RBA::DeviceClassDiode) || c.is_a?(RBA::DeviceClassBJT3Transistor) ||
         c.is_a?(RBA::DeviceClassCapacitor)
        c.equal_parameters = RBA::EqualDeviceParameters::ignore(c.parameter_id("A")) rescue nil
      end
    end
  end
  # LVS CHECK PORT NAMES YES: named top level ports must pair by name
  tcn = $topcell || source.cell_name
  ltc = netlist.circuit_by_name(tcn)
  stc2 = schematic.circuit_by_name(tcn)
  if ltc && stc2
    snames = {}
    stc2.each_pin { |p| snames[p.name] = true if p.name != "" }
    ltc.each_pin do |p|
      next if p.name == "" || !snames[p.name]
      same_nets!(tcn, p.name, p.name)
    end
  end
  ok = compare
  if ok
    log("INFO : Congratulations! Netlists match.")
  else
    log("ERROR : Netlists don't match")
  end
end
log("SVRF LVS: total runtime #{'%.1f' % (Time.now - $sv_exec_start)} s")
'''


def generate(svrf, out, name='ICS55'):
    deck = P.Deck(svrf)
    g = LvsGen(deck)
    g.gen_stmts(deck.stmts, 0, '$sv_G')
    defines = []
    P.walk_stmts(deck.stmts, lambda s, p: defines.append(s[1]) if s[0] == 'define' else None)
    ov = []
    for d in sorted(set(x.upper() for x in defines)):
        ov.append('$sv_overrides[%s] = $%s.to_s if defined?($%s) && $%s' % (rb_str(d), d, d, d))
    text = PRELUDE.format(name=name, src=os.path.basename(svrf), overrides='\n'.join(ov))
    text += open(os.path.join(HERE, 'svrf_runtime.rb')).read() + '\n'
    text += open(os.path.join(HERE, 'svrf_lvs_runtime.rb')).read() + '\n'
    text += '$sv_G = SvScope.new(self, nil, "GLOBAL")\n'
    text += '\n'.join(g.out) + '\n'
    text += POSTLUDE.replace('{mos_err}', repr(float(deck.variables.get('mos_err', 0.1)))) \
                    .replace('{res_err}', repr(float(deck.variables.get('res_err', 0.1))))
    open(out, 'w').write(text)
    return g, deck


if __name__ == '__main__':
    g, deck = generate(sys.argv[1], sys.argv[2])
    print('parse errors: %d, unsupported: %d' % (len(deck.errors), len(g.unsupported)))
