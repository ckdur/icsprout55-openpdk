#!/usr/bin/env python3
"""
v2cdl.py netlist.v top out.cdl lib1.cdl [lib2.cdl ...]

Convert a flat structural (gate level, powered) Verilog netlist into a CDL
netlist for LVS. Pin order of the cells is taken from the library CDLs,
which are appended to the output.
"""
import re
import sys


def read_subckts(path):
    pins = {}
    cur = None
    for line in open(path, encoding='latin-1'):
        if line.startswith('+') and cur:
            pins[cur] += line[1:].split()
            continue
        m = re.match(r'\s*\.subckt\s+(\S+)(.*)', line, re.I)
        if m:
            cur = m.group(1)
            if cur not in pins:
                pins[cur] = [p for p in m.group(2).split() if '=' not in p]
            else:
                cur = None
        else:
            cur = None
    return pins


def net(n):
    n = n.strip()
    if n.startswith('\\'):
        n = n[1:].strip()
    return n.replace(' ', '')


def main():
    v, top, out = sys.argv[1:4]
    libs = sys.argv[4:]
    pins = {}
    for l in libs:
        for k, p in read_subckts(l).items():
            pins.setdefault(k, p)
    txt = open(v).read()
    txt = re.sub(r'//.*', '', txt)
    txt = re.sub(r'/\*.*?\*/', '', txt, flags=re.S)
    m = re.search(r'module\s+%s\s*\((.*?)\);(.*?)endmodule' % re.escape(top), txt, re.S)
    if not m:
        raise SystemExit('module %s not found' % top)
    body = m.group(2)
    ports = []
    for d in re.finditer(r'^\s*(input|output|inout)\s+(\[(\d+):(\d+)\])?\s*([^;]+);', body, re.M):
        for nm in d.group(5).split(','):
            nm = net(nm)
            if d.group(2):
                a, b = int(d.group(3)), int(d.group(4))
                step = -1 if a > b else 1
                ports += ['%s[%d]' % (nm, i) for i in range(a, b + step, step)]
            else:
                ports.append(nm)
    lines = ['* generated by v2cdl.py from %s' % v, '.SUBCKT %s %s' % (top, ' '.join(ports))]
    for inst in re.finditer(r'^\s*([A-Za-z_]\w*)\s+(\\\S+\s|[A-Za-z_][\w$]*)\s*\((.*?)\)\s*;', body, re.S | re.M):
        cell, name, conn = inst.group(1), net(inst.group(2)), inst.group(3)
        if cell in ('input', 'output', 'inout', 'wire', 'assign', 'module'):
            continue
        if cell not in pins:
            raise SystemExit('cell %s not found in libraries' % cell)
        cm = {}
        for c in re.finditer(r'\.(\w+)\s*\(\s*([^)]*)\)', conn):
            cm[c.group(1)] = net(c.group(2))
        nets = []
        for p in pins[cell]:
            n = cm.get(p)
            if not n:
                n = '%s_%s_unconnected' % (name, p)
            nets.append(n)
        lines.append('X%s %s %s' % (name, ' '.join(nets), cell))
    lines.append('.ENDS')
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')
        for l in libs:
            f.write(open(l, encoding='latin-1').read())
            f.write('\n')


if __name__ == '__main__':
    main()
