#!/usr/bin/env python3
"""Generate OpenRCX extraction rules from a StarRC ITF.

Every OpenRCX context (OVER u, UNDER o, OVER u UNDER o, u/o = 0 is the substrate)
is solved as a 2D cross-section with FasterCap (patterns.py: three parallel
lines, middle one excited, neighbouring layers as ground planes; set $FASTERCAP
to the binary), on the physical geometry, i.e.
the drawn width/spacing times the ITF HALF_NODE_SCALE_FACTOR.  The tables are
written in drawn units: separations and widths as drawn, capacitance and
resistance per drawn length (the per-unit-length values times the shrink).

Rule conventions (src/rcx, extRCModel::readRCvalues / extMeasureRC):
  * a row is ``dist cc fringe res``, in um and fF/nm (= pF/um) / ohm/nm;
  * cc is the coupling to ONE neighbour at distance ``dist``;
  * fringe is half the ground capacitance of the line (the extractor adds one
    fringe per side);
  * the last row of a table is used for a line without neighbours, so the table
    ends with the isolated line (cc = 0) at a large distance;
  * no interpolation between widths: a wire uses the next lower table width.

DIAGUNDER tables are not generated (DIAGMODEL off).

Usage: itf2rcx.py <itf> <out.rules> [-j N] [--csv dump.csv]
"""

import argparse
import multiprocessing as mp
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import itf  # noqa: E402
import patterns  # noqa: E402

# OpenRCX metal index -> (ITF conductor, LEF layer, drawn min width, drawn min spacing)
LAYERS = [
    ("M1", "MET1", 0.09, 0.09),
    ("M2", "MET2", 0.10, 0.10),
    ("M3", "MET3", 0.10, 0.10),
    ("M4", "MET4", 0.10, 0.10),
    ("M5", "MET5", 0.10, 0.10),
    ("TM", "T4M2", 0.40, 0.40),
    ("RDL", "RDL", 3.00, 2.00),
]
NMET = len(LAYERS)

WIDTH_MULT = [1, 1.5, 2, 3, 5, 10, 20]
SPACE_MULT = [1, 1.25, 1.5, 2, 3, 4, 6, 10, 20]
ISO_MULT = 50  # distance of the final (isolated line) row
WIDTH_MULT_RDL = [1, 2, 4]


def widths(m):
    w = LAYERS[m - 1][2]
    mult = WIDTH_MULT_RDL if LAYERS[m - 1][0] == "RDL" else WIDTH_MULT
    return [round(w * k, 4) for k in mult]


MAX_SPACE = 8.0  # um; coupling beyond this is negligible on every layer


def spacings(m):
    s = LAYERS[m - 1][3]
    return [round(s * k, 4) for k in SPACE_MULT if s * k <= MAX_SPACE]


def contexts(m):
    """(kind, under, over) for metal m in the order the rules file needs."""
    over = [("OVER", u, 0) for u in range(0, m)]
    under = [("UNDER", 0, o) for o in range(m + 1, NMET + 1)]
    ou = [("OVERUNDER", u, o) for u in range(1, m) for o in range(m + 1, NMET + 1)]
    return over, under, ou


_STACK = None


def _init(path):
    global _STACK
    _STACK = itf.read_itf(path)


def _job(args):
    m, u, o, w, s = args
    st = _STACK
    sh = st.half_node
    name = LAYERS[m - 1][0]
    un = LAYERS[u - 1][0] if u else None
    ov = LAYERS[o - 1][0] if o else None
    # lateral extent: shielded patterns settle at 4 um, open ones at ~3x height
    zt = st.conductors[name].zt
    half = 4.0 if ov else min(16.0, max(4.0, 3 * zt))
    kw = dict(under=un, over=ov, half_width=half)
    try:
        r = patterns.pattern_caps(st, name, w * sh, None if s is None else s * sh, **kw)
    except RuntimeError:
        # out of memory on the largest domains: retry once on a twice coarser mesh
        mesh = 2 * patterns.MESH_ABS * min(4.0, max(1.0, st.conductors[name].wmin / 0.09))
        print(f"  retry {args} with mesh {mesh}", file=sys.stderr)
        r = patterns.pattern_caps(st, name, w * sh, None if s is None else s * sh, mesh_abs=mesh, **kw)
    return args, r


def build_jobs():
    jobs = []
    for m in range(NMET, 0, -1):  # slowest (thick, high) layers first
        a, b, c = contexts(m)
        for _, u, o in a + b + c:
            for w in widths(m):
                for s in spacings(m):
                    jobs.append((m, u, o, w, s))
                jobs.append((m, u, o, w, None))
    return jobs


def res_per_nm(stack, m, w):
    """ohm per drawn nm of a drawn width w line (length and width shrink alike)."""
    return stack.conductors[LAYERS[m - 1][0]].rpsq / w / 1000.0


def write_rules(path, stack, res):
    sh = stack.half_node
    out = []
    p = out.append
    p("Extraction Rules for OpenRCX")
    p(f"# generated by generate_rcx_rules/itf2rcx.py from {stack.technology}")
    p(f"# 2D field solution of the ITF stack, half node shrink {sh}, T = {stack.temperature} C")
    p("")
    p(f"LayerCount {NMET}")
    p("DensityRate 1  0")
    p("")
    p("DensityModel 0")

    def table(m, u, o, res_only=False):
        for w in widths(m):
            r = res_per_nm(stack, m, w)
            if res_only:
                # (dist1, dist2) grid as OpenRCX writes it: the reader only builds its
                # lookup tables for more than one row (a single row crashes
                # extDistRCTable::getComputeRC_res).  R is distance independent here.
                d = spacings(m)[:5]
                rows = [(0, 0)] + [(a, b) for i, a in enumerate([0] + d) for b in d[max(i - 1, 0):]]
                rows.append((d[-1], 0))
                p(f"DIST count {len(rows)} width {w:g}")
                for a, b in rows:
                    p(f"{a:g} {b:g} 0 {r:.6g}")
                p("END DIST")
                p("")
                continue
            rows = []
            for s in spacings(m):
                _, cc, cg = res[(m, u, o, w, s)]
                rows.append((s, cc, cg))
            _, _, cg = res[(m, u, o, w, None)]
            rows.append((round(LAYERS[m - 1][3] * ISO_MULT, 4), 0.0, cg))
            p(f"DIST count {len(rows)} width {w:g}")
            for s, cc, cg in rows:
                p(f"{s:g} {sh * cc / 1000:.6g} {sh * cg / 2 / 1000:.6g} {r / 2:.6g}")
            p("END DIST")
            p("")

    def width_header(m, key):
        p("")
        p(f"Metal {m} {key}")
        p(f"WIDTH Table {len(widths(m))} entries:  " + " ".join(f"{w:g}" for w in widths(m)))
        p("")

    for m in range(1, NMET + 1):
        over, under, ou = contexts(m)
        width_header(m, "RESOVER")
        for _, u, o in over:
            p(f"Metal {m} RESOVER {u}")
            table(m, u, o, res_only=True)
        width_header(m, "OVER")
        for _, u, o in over:
            p(f"Metal {m} OVER {u}")
            table(m, u, o)
        if m < NMET:
            width_header(m, "UNDER")
            for _, u, o in under:
                p(f"Metal {m} UNDER {o}")
                table(m, u, o)
        if 1 < m < NMET:
            width_header(m, "OVERUNDER")
            for _, u, o in ou:
                p(f"Metal {m} OVER {u} UNDER {o}")
                table(m, u, o)
    p("END DensityModel 0")
    p("")
    open(path, "w").write("\n".join(out))


VIA_LEF = {"V1": "VIA1", "V2": "VIA2", "V3": "VIA3", "V4": "VIA4", "TV": "T4V2", "RV": "RV"}


def write_tcl(path, stack, res, glob, temp):
    """LAYERS_RC / VIAS_R for placement and global routing estimates, in liberty
    units (kohm/um, pF/um, kohm per cut).  The wire is a minimum width line with
    neighbours at twice the minimum spacing on both sides, averaged between an
    empty (substrate only) and a dense (planes on both adjacent layers)
    environment; resistance at ``temp``."""
    sh = stack.half_node
    dt = temp - stack.temperature
    out = [
        f"# {stack.technology}, {temp:g} C: generate_rcx_rules/itf2rcx.py --tcl",
        "# min width line, neighbours at 2x min spacing, mean of empty / dense surroundings",
    ]
    for m in range(1, NMET + 1):
        name, lef, w, s = LAYERS[m - 1]
        c = stack.conductors[name]
        s2 = round(2 * s, 4)
        empty = res[(m, 0, 0, w, s2)][0]
        u = m - 1
        o = m + 1 if m < NMET else 0
        dense = res[(m, u, o, w, s2)][0]
        cap = sh * (empty + dense) / 2 / 1000  # fF/um physical -> pF per drawn um
        r = c.rpsq * (1 + c.crt1 * dt + c.crt2 * dt * dt) / w / 1000  # kohm per drawn um
        out.append(f'dict set ::env(LAYERS_RC) "{glob}" {lef} res {r:.6g}')
        out.append(f'dict set ::env(LAYERS_RC) "{glob}" {lef} cap {cap:.6g}')
    for v, lef in VIA_LEF.items():
        out.append(f'dict set ::env(VIAS_R) "{glob}" {lef} res {stack.vias[v].rpv / 1000:.6g}')
    open(path, "w").write("\n".join(out) + "\n")


def read_csv(path):
    res = {}
    for ln in open(path).read().splitlines()[1:]:
        m, u, o, w, s, ct, cc, cg = ln.split(",")
        key = (int(m), int(u), int(o), float(w), float(s) if s else None)
        res[key] = (float(ct), float(cc), float(cg))
    return res


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("itf")
    ap.add_argument("rules")
    ap.add_argument("-j", type=int, default=os.cpu_count())
    ap.add_argument("--csv", help="dump the raw per-pattern solutions (fF/um, physical)")
    ap.add_argument("--from-csv", help="reuse the solutions of a previous --csv instead of solving")
    ap.add_argument("--tcl", help="also write LAYERS_RC / VIAS_R for LibreLane to this file")
    ap.add_argument("--glob", default="*", help="IPVT corner wildcard for --tcl")
    ap.add_argument("--temp", type=float, default=25.0, help="temperature (C) of the --tcl resistances")
    a = ap.parse_args()
    stack = itf.read_itf(a.itf)
    if a.from_csv:
        res = read_csv(a.from_csv)
    else:
        # results are appended to <csv>.cache as they arrive, so a killed run resumes
        cache = (a.csv or a.rules) + ".cache"
        res = read_csv(cache) if os.path.exists(cache) else {}
        jobs = [j for j in build_jobs() if j not in res]
        print(
            f"{stack.technology}: {len(jobs)} cross-sections ({len(res)} cached) on {a.j} processes",
            file=sys.stderr,
        )
        new = not os.path.exists(cache)
        with open(cache, "a") as cf, mp.Pool(a.j, initializer=_init, initargs=(a.itf,)) as pool:
            if new:
                cf.write("metal,under,over,w_drawn,s_drawn,ctot,cc,cg\n")
            for i, ((m, u, o, w, s), v) in enumerate(pool.imap_unordered(_job, jobs, chunksize=1)):
                res[(m, u, o, w, s)] = v
                cf.write(f"{m},{u},{o},{w},{'' if s is None else s},{v[0]:.6g},{v[1]:.6g},{v[2]:.6g}\n")
                cf.flush()
                if i % 100 == 0:
                    print(f"  {i}/{len(jobs)}", file=sys.stderr)
    if a.csv:
        with open(a.csv, "w") as f:
            f.write("metal,under,over,w_drawn,s_drawn,ctot,cc,cg\n")
            for (m, u, o, w, s), (ct, cc, cg) in sorted(res.items(), key=lambda kv: (kv[0][:4], kv[0][4] or 1e9)):
                f.write(f"{m},{u},{o},{w},{'' if s is None else s},{ct:.6g},{cc:.6g},{cg:.6g}\n")
    write_rules(a.rules, stack, res)
    if a.tcl:
        write_tcl(a.tcl, stack, res, a.glob, a.temp)


if __name__ == "__main__":
    main()
