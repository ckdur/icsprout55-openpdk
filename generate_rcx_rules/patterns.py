"""FasterCap 2D cross-section patterns on an ITF stack.

pattern_caps() writes a FasterCap 2D input for ``nwires`` parallel lines of width w /
spacing s (physical, i.e. already shrunk, dimensions) on conductor ``layer``, with
optional ground planes on the layer below (``under``) and above (``over``) and the
substrate at z = 0, runs FasterCap and returns per um of length (fF/um):

    ctot  total capacitance of the middle line (all other conductors grounded)
    cc    coupling to ONE neighbour (average of both sides; 0 if isolated)
    cg    everything else (substrate, planes, far lines): ctot - 2*cc

FasterCap 2D conventions used here:
  * ``C <file> <outperm> x y [+]``: conductor surface segments with the permittivity
    outside of them; ``+`` joins the next C statement to the same conductor, so a
    line crossing several dielectric layers is made of one piece per layer;
  * ``D <file> <outperm> <inperm> x y xref yref``: dielectric interface, the
    reference point lies on the outperm side;
  * the last conductor is the reference and does not appear in the matrix, so the
    substrate is written last;
  * 2D capacitance per unit length is scale free: coordinates are given in um and
    the result (F/m) times 1e9 is fF/um.
"""

import os
import re
import subprocess
import tempfile

FASTERCAP = os.environ.get("FASTERCAP", "FasterCap")
# absolute FasterCap panel scale (um): -m is relative to the bounding box, so
# -m = MESH_ABS / (2 * half width) keeps the discretisation the same for every
# domain size.  0.04 um is within 0.5% of the converged M2 min-pitch solution.
MESH_ABS = float(os.environ.get("FASTERCAP_MESH_ABS", "0.04"))
HALF_WIDTH = 4.0  # default lateral half extent of substrate, planes, interfaces (um)
EPS = 1e-6


def _regions(stack):
    """Merge adjacent dielectrics of equal permittivity: [(zb, zt, er)]."""
    out = []
    for d in stack.dielectrics:
        if out and abs(out[-1][2] - d.er) < 1e-9 and abs(out[-1][1] - d.zb) < 1e-9:
            out[-1] = (out[-1][0], d.zt, d.er)
        else:
            out.append((d.zb, d.zt, d.er))
    return out


def _er(regions, z):
    for zb, zt, er in regions:
        if zb <= z < zt:
            return er
    return 1.0  # air above the stack


def build_input(stack, rects, L):
    """FasterCap list file text; rects = [(x0, x1, z0, z1)], the last one is the
    reference (substrate); L is the lateral half extent of the interfaces."""
    reg = _regions(stack)
    zif = [zb for zb, _, _ in reg[1:]] + [reg[-1][1]]  # interfaces incl. top/air
    main = ["* 2D cross-section, generated by generate_rcx_rules/patterns.py", ""]  # FasterCap needs "2D" on line 1
    files = []
    nf = [0]

    def newfile(segs, name):
        nf[0] += 1
        fn = f"f{nf[0]}.txt"
        body = [f"File {fn}", "", f"0 {name}", "*"]
        body += [f"S {name} {a:.6f} {b:.6f} {c:.6f} {d:.6f}" for a, b, c, d in segs]
        body += ["", "End"]
        files.append("\n".join(body))
        return fn

    for k, (x0, x1, z0, z1) in enumerate(rects):
        name = f"c{k}"
        pieces = []  # (segment list, outperm)
        pieces.append(([(x0, z0, x1, z0)], _er(reg, z0 - EPS)))
        pieces.append(([(x0, z1, x1, z1)], _er(reg, z1 + EPS)))
        cuts = [z0] + [z for z in zif if z0 + EPS < z < z1 - EPS] + [z1]
        for za, zb in zip(cuts[:-1], cuts[1:]):
            pieces.append(([(x0, za, x0, zb), (x1, za, x1, zb)], _er(reg, (za + zb) / 2)))
        for i, (segs, er) in enumerate(pieces):
            fn = newfile(segs, name)
            more = " +" if i < len(pieces) - 1 else ""
            main.append(f"C {fn} {er:g} 0 0{more}")
        main.append("")

    for z in zif:
        eb, ea = _er(reg, z - EPS), _er(reg, z + EPS)
        if abs(eb - ea) < 1e-9:
            continue
        blocked = sorted((x0, x1) for x0, x1, z0, z1 in rects if z0 - EPS <= z <= z1 + EPS)
        segs = []
        x = -L
        for a, b in blocked:
            a, b = max(a, -L), min(b, L)
            if a > x + EPS:
                segs.append((x, z, a, z))
            x = max(x, b)
        if x < L - EPS:
            segs.append((x, z, L, z))
        if not segs:
            continue
        xr = (segs[0][0] + segs[0][2]) / 2
        fn = newfile(segs, "diel")
        main.append(f"D {fn} {ea:g} {eb:g} 0 0 {xr:.6f} {z + 1e-3:.6f}")

    return "\n".join(main) + "\n\n" + "\n\n".join(files) + "\n"


_DIM = re.compile(r"Dimension (\d+) x \d+")


def run_fastercap(text, mesh, keep=None):
    """mesh: FasterCap -m value (relative to the bounding box).  The automatic mode
    (-a) is not used: on these geometries (long planes / thin dielectric layers)
    it stops at under-refined meshes and returns results off by up to 40%.
    -f0.05 keeps the links in memory: FasterCap underestimates the free memory and
    its out-of-core mode fails on these inputs."""
    with tempfile.TemporaryDirectory() as d:
        lst = os.path.join(d, "p.lst")
        open(lst, "w").write(text)
        r = subprocess.run(
            [FASTERCAP, "-b", lst, f"-m{mesh:.6g}", "-t0.001", "-f0.05"], cwd=d, capture_output=True, text=True
        )
        if keep:
            open(keep, "w").write(text)
    # one matrix per auto-refinement iteration; the last one is the converged one
    blocks = r.stdout.split("Capacitance matrix is:")
    if len(blocks) < 2:
        raise RuntimeError("FasterCap failed:\n" + r.stdout[-2000:] + r.stderr[-2000:])
    lines = blocks[-1].strip().splitlines()
    n = int(_DIM.match(lines[0]).group(1))
    rows = [list(map(float, ln.split()[1:])) for ln in lines[1 : n + 1]]
    return [[v * 1e9 for v in row] for row in rows]  # F/m -> fF/um


def pattern_caps(
    stack, layer, w, s, under=None, over=None, nwires=3, half_width=None, mesh_abs=None, keep=None
):
    """mesh_abs: absolute panel scale in um (default MESH_ABS scaled with the
    layer's minimum width relative to M2, i.e. coarser on the thick top layers)."""
    c = stack.conductors[layer]
    if s is None:
        nwires = 1
    n = nwires // 2
    rects = []
    for k in [0] + [j for i in range(1, n + 1) for j in (-i, i)]:
        x0 = k * (w + (s or 0)) - w / 2
        rects.append((x0, x0 + w, c.zb, c.zt))
    L = half_width or HALF_WIDTH
    L += n * (w + (s or 0)) + w / 2  # margin beyond the outer lines
    for name in (under, over):
        if name:
            p = stack.conductors[name]
            rects.append((-L, L, p.zb, p.zt))
    rects.append((-L, L, -0.1, 0.0))  # substrate, reference (last)
    if mesh_abs is None:
        mesh_abs = MESH_ABS * min(4.0, max(1.0, c.wmin / 0.09))
    C = run_fastercap(build_input(stack, rects, L), mesh_abs / (2 * L), keep=keep)
    ctot = C[0][0]
    cc = -(C[0][1] + C[0][2]) / 2 if nwires > 1 else 0.0
    return ctot, cc, ctot - 2 * cc
